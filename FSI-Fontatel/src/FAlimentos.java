    private void BAgregarfotoActionPerformed(java.awt.event.ActionEvent evt) {
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir"));
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            try {
                File archivo = fc.getSelectedFile();
                fotoAlimento = Files.readAllBytes(archivo.toPath());
                ImageIcon foto = new ImageIcon(fotoAlimento);
                LFoto.setIcon(new ImageIcon(Conexion.escalarImagen(foto.getImage(), 250, 300)));
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "No se pudo abrir la foto");
            }
        }
    }

    private void BRegistrarActionPerformed(java.awt.event.ActionEvent evt) {
        if (fotoAlimento == null) {
            JOptionPane.showMessageDialog(this, "Primero agrega una foto");
            return;
        }

        String id = TAlimentos.getText();
        String nombre = TNombre.getText();
        String descripcion = TDescripcion.getText();
        String precio = TPrecio.getText();
        String categoria = CCategoria.getSelectedItem().toString();
        String estado = CEstado.getSelectedItem().toString();

        Alimentos alimento = new Alimentos(id, nombre, descripcion, precio,
                fotoAlimento, categoria, estado);
        if (alimento.insertar(cnx.getCon()) == 1) {
            cnx.entablar(Alimentos.todos, Tabla, 10, 15, 18, 10, 25, 12, 10);
            JOptionPane.showMessageDialog(this, "Alimento registrado");
            TAlimentos.setText("");
            TNombre.setText("");
            TDescripcion.setText("");
            TPrecio.setText("");
            LFoto.setIcon(null);
            fotoAlimento = null;
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el alimento");
        }
    }

    private void TablaMousePressed(java.awt.event.MouseEvent evt) {
        int renglon = Tabla.getSelectedRow();
        if (renglon >= 0) {
            DefaultTableModel modelo = (DefaultTableModel) Tabla.getModel();
            TAlimentos.setText(modelo.getValueAt(renglon, 0).toString());
            TNombre.setText(modelo.getValueAt(renglon, 1).toString());
            TDescripcion.setText(modelo.getValueAt(renglon, 2).toString());
            TPrecio.setText(modelo.getValueAt(renglon, 3).toString());
            CCategoria.setSelectedItem(modelo.getValueAt(renglon, 5).toString());
            CEstado.setSelectedItem(modelo.getValueAt(renglon, 6).toString());
            Object imagen = modelo.getValueAt(renglon, 4);
            if (imagen instanceof ImageIcon) {
                LFoto.setIcon(new ImageIcon(Conexion.escalarImagen(
                        ((ImageIcon) imagen).getImage(), 250, 300)));
            }
        }
    }

